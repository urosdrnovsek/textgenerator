/**
 * Writes tests/golden/runs.json: the characterization fingerprint of every
 * bundled text's styled output (see scripts/lib/golden-runs.mjs).
 *
 * Regenerate ONLY in a commit of its own whose message says which visible
 * change was intended, so the golden diff documents it:
 *   node scripts/dump-golden-runs.mjs
 * With --explain <lang:id>, prints that entry's canonical styled output for
 * every combination instead (for diffing against another checkout).
 */

import { writeFile } from 'node:fs/promises';
import { COMBOS, comboLabel, computeGolden, loadEntries, buildParagraphs, canonicalParagraphs } from './lib/golden-runs.mjs';

const root = new URL('../', import.meta.url);
const explainIndex = process.argv.indexOf('--explain');

if (explainIndex !== -1) {
  const key = process.argv[explainIndex + 1];
  const entry = (await loadEntries(root)).find((e) => `${e.language}:${e.id}` === key);
  if (!entry) {
    console.error(`No bundled entry "${key}".`);
    process.exit(1);
  }
  for (const combo of COMBOS) {
    console.log(`=== ${comboLabel(combo)}`);
    console.log(canonicalParagraphs(buildParagraphs(entry, combo)));
  }
} else {
  const entries = await computeGolden(root);
  const golden = { note: 'Generated by scripts/dump-golden-runs.mjs — do not edit by hand.', combos: COMBOS.map(comboLabel), entries };
  await writeFile(new URL('tests/golden/runs.json', root), `${JSON.stringify(golden, null, 0)}\n`);
  console.log(`Wrote tests/golden/runs.json: ${Object.keys(entries).length} entries × ${COMBOS.length} combinations.`);
}
